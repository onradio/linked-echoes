#!/usr/bin/env python3
"""Stage 6 (part 2) — generate the article deliverables (spec §9).

Reads only `data/results/` and writes LaTeX into `data/results/latex/`. Every
number comes from `score.py`; nothing here recomputes or hand-edits a value.

    python report.py

Produces
--------
figure_degradation.tex   accuracy vs k, one line per system (pgfplots)
figure_degradation.pdf   the same figure as vector PDF (+ .png preview)
figure_attribution.pdf   error attribution per system (+ .png preview)
table1_main.tex          main comparison at the headline k
table2_per_type.tex      per entity type
table3_hard_cases.tex    qualitative hard cases
macros.tex               \\newcommand for every number quoted in prose

The methodology/results narrative is *not* generated: it lives in `summary.md`
at the top of this directory and is written by hand, because prose about why an
experiment was designed a certain way is not something a script should assemble.
Numbers quoted there should be taken from `macros.tex` or the CSVs.

The figure is emitted as pgfplots rather than a raster: it is vector, it picks
up the document's fonts, and it needs no Python plotting stack. Add
`\\usepackage{pgfplots}` and `\\usepackage{booktabs}` to the preamble.
"""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "data" / "results"
OUT = RESULTS / "latex"

SYSTEM_LABEL = {
    "S0": r"$S_0$ retrieval rank-1",
    "S1": r"$S_1$ symbolic only",
    "S2": r"$S_2$ neural",
    "S3": r"$S_3$ neuro-symbolic (ours)",
}
PLAIN_LABEL = {"S0": "$S_0$ retrieval rank-1", "S1": "$S_1$ symbolic only",
               "S2": "$S_2$ neural", "S3": "$S_3$ neuro-symbolic (ours)"}

# Categorical hues taken unchanged, in documented order, from the data-viz
# reference palette. S0 is a baseline reference rather than a compared system,
# so it takes neutral ink and a dashed line; that leaves the three systems under
# comparison on slots 1-3, the subset documented as clearing the separation
# floors on every pair rather than only on adjacent ones.
SERIES_HEX = {"S0": "#6f6e6a", "S1": "#2a78d6", "S2": "#eb6834", "S3": "#1baf7a"}
# Secondary encoding: marker and dash pattern carry identity too, so the figure
# survives greyscale printing and colour-vision deficiency without relying on hue.
SERIES_MARKER = {"S0": "s", "S1": "^", "S2": "D", "S3": "o"}
SERIES_DASH = {"S0": (4, 3), "S1": (6, 2), "S2": (2, 2), "S3": ()}
INK, INK_MUTED, GRID = "#0b0b0b", "#52514e", "#d8d7d2"

# Error-attribution categories, in the precedence order of spec §8.3.
CAUSES = ["retrieval_miss", "validator_rejection", "llm_misselection",
          "llm_false_abstention", "spurious_link"]
CAUSE_LABEL = {
    "retrieval_miss": "retrieval miss",
    "validator_rejection": "validator rejection",
    "llm_misselection": "wrong selection",
    "llm_false_abstention": "false abstention",
    "spurious_link": "spurious link",
}
CAUSE_HEX = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]

# pgfplots equivalents of the same assignment
COLOURS = {"S0": "black!45", "S1": "blue!65!black",
           "S2": "orange!85!black", "S3": "teal!80!black"}
MARKS = {"S0": "square*", "S1": "triangle*", "S2": "diamond*", "S3": "*"}


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def tex_escape(s):
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"),
                 ("$", r"\$"), ("’", "'"), ("“", "``"), ("”", "''")):
        s = s.replace(a, b)
    return s


def mean_sd(values):
    n = len(values)
    if n == 0:
        return 0.0, 0.0
    m = sum(values) / n
    var = sum((v - m) ** 2 for v in values) / (n - 1) if n > 1 else 0.0
    return m, var ** 0.5


