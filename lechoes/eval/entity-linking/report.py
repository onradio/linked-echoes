def figure(per_cell, stats, path):
    """Accuracy vs k, error bars = SD over runs (spec §9)."""
    by = defaultdict(lambda: defaultdict(list))
    for r in per_cell:
        by[r["system"]][int(r["k"])].append(float(r["accuracy"]))
    ks = sorted({int(r["k"]) for r in per_cell if r["system"] != "S0"})

    lines = [
        "% Accuracy vs retrieval depth k. Generated by report.py — do not edit.",
        "% Requires: \\usepackage{pgfplots} \\pgfplotsset{compat=1.18}",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"    width=\linewidth, height=6.2cm,",
        f"    xlabel={{Retrieval depth $k$}}, ylabel={{Accuracy}},",
        f"    xtick={{{','.join(str(k) for k in ks)}}}, xmode=log, log basis x=2,",
        r"    xticklabels={5,10,25,50},",
        r"    ymin=0.55, ymax=1.0, grid=major, grid style={gray!20},",
        r"    legend pos=south west, legend cell align=left,",
        r"    legend style={font=\small, fill=white, fill opacity=0.85,"
        r" text opacity=1},",
        r"]",
    ]
    # S0 is k-independent: draw as a horizontal reference line.
    s0 = by.get("S0")
    if s0:
        acc0 = list(s0.values())[0][0]
        lines += [
            f"\\addplot[{COLOURS['S0']}, dashed, thick, forget plot] "
            f"coordinates {{({ks[0]},{acc0:.4f}) ({ks[-1]},{acc0:.4f})}};",
            f"\\addlegendimage{{{COLOURS['S0']}, dashed, thick}}",
            f"\\addlegendentry{{{SYSTEM_LABEL['S0']}}}",
        ]
    for system in ("S1", "S2", "S3"):
        if system not in by:
            continue
        pts = []
        for k in ks:
            m, sd = mean_sd(by[system][k])
            pts.append(f"({k},{m:.4f}) +- (0,{sd:.4f})")
        lines += [
            f"\\addplot[{COLOURS[system]}, thick, mark={MARKS[system]}, "
            f"error bars/.cd, y dir=both, y explicit] coordinates {{"
            + " ".join(pts) + "};",
            f"\\addlegendentry{{{SYSTEM_LABEL[system]}}}",
        ]
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _mpl():
    """Configure matplotlib for print: vector output, recessive furniture."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({
        "figure.dpi": 150, "savefig.dpi": 300,
        "savefig.bbox": "tight", "savefig.pad_inches": 0.02,
        "pdf.fonttype": 42, "ps.fonttype": 42,     # embed real fonts, not paths
        "font.size": 9, "axes.titlesize": 10, "axes.labelsize": 9,
        "legend.fontsize": 8, "xtick.labelsize": 8.5, "ytick.labelsize": 8.5,
        "axes.edgecolor": GRID, "axes.labelcolor": INK,
        "text.color": INK, "xtick.color": INK_MUTED, "ytick.color": INK_MUTED,
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    })
    return plt


def figure_pdf(per_cell, stats, stem):
    """Accuracy vs k as PDF+PNG (spec §9 figure), vector for LaTeX inclusion."""
    plt = _mpl()
    by = defaultdict(lambda: defaultdict(list))
    for r in per_cell:
        by[r["system"]][int(r["k"])].append(float(r["accuracy"]))
    ks = sorted({int(r["k"]) for r in per_cell if r["system"] != "S0"})
    x = list(range(len(ks)))                    # even spacing, labelled by k

    fig, ax = plt.subplots(figsize=(5.6, 3.5))
    if "S0" in by:                              # k-independent baseline
        acc0 = list(by["S0"].values())[0][0]
        ax.plot(x, [acc0] * len(x), color=SERIES_HEX["S0"], lw=1.6,
                dashes=SERIES_DASH["S0"], marker=SERIES_MARKER["S0"],
                ms=4.5, mfc="white", mew=1.2, label=PLAIN_LABEL["S0"], zorder=2)
        ax.annotate("S0", (x[-1], acc0), textcoords="offset points",
                    xytext=(8, -2), color=INK, fontsize=8.5, weight="bold")
    for system in ("S1", "S2", "S3"):
        if system not in by:
            continue
        means = [mean_sd(by[system][k])[0] for k in ks]
        sds = [mean_sd(by[system][k])[1] for k in ks]
        ax.errorbar(x, means, yerr=sds, color=SERIES_HEX[system], lw=2.0,
                    dashes=SERIES_DASH[system], marker=SERIES_MARKER[system],
                    ms=6, mfc="white", mew=1.6, capsize=3, elinewidth=1.2,
                    label=PLAIN_LABEL[system], zorder=3)
        # Direct label at the right end: identity is never colour-alone, and the
        # aqua slot sits below 3:1 on white, which obliges visible labelling.
        ax.annotate(system, (x[-1], means[-1]), textcoords="offset points",
                    xytext=(8, -2), color=INK, fontsize=8.5, weight="bold")

    ax.set_xticks(x, [str(k) for k in ks])
    ax.set_xlim(-0.25, len(ks) - 1 + 0.62)
    ax.set_xlabel("Retrieval depth $k$")
    ax.set_ylabel("Accuracy")
    # Bound to the data rather than to 0: the comparison is between systems, and
    # a floor of 0 would compress every difference the figure exists to show.
    lo = min(v for s in by.values() for vals in s.values() for v in vals)
    ax.set_ylim(max(0.0, lo - 0.05), 1.0)
    ax.set_axisbelow(True)
    ax.grid(axis="x", visible=False)
    # Below the axes, not over them: in-panel placement covered the S0 baseline.
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.20), ncol=2,
              frameon=False, handlelength=2.6, columnspacing=1.6,
              handletextpad=0.6)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(f"{stem}.{ext}")
    plt.close(fig)


def figure_attribution_pdf(attribution, stats, stem):
    """Error attribution as a horizontal stacked bar (spec §8.3 / §9)."""
    plt = _mpl()
    rows = [a for a in attribution if a["system"] in ("S0", "S1", "S2", "S3")]
    rows.sort(key=lambda a: ["S3", "S2", "S1", "S0"].index(a["system"]))
    labels = [PLAIN_LABEL[a["system"]] for a in rows]
    y = list(range(len(rows)))

    fig, ax = plt.subplots(figsize=(5.6, 2.7))
    left = [0.0] * len(rows)
    for i, cause in enumerate(CAUSES):
        vals = [float(a.get(cause, 0) or 0) for a in rows]
        if not any(vals):
            continue
        ax.barh(y, vals, left=left, height=0.62, color=CAUSE_HEX[i],
                label=CAUSE_LABEL[cause],
                # 2px surface gap between stacked segments
                edgecolor="white", linewidth=1.4, zorder=3)
        left = [l + v for l, v in zip(left, vals)]
    for yi, total in zip(y, left):
        ax.annotate(f"{total:.0f}", (total, yi), textcoords="offset points",
                    xytext=(5, -3), color=INK_MUTED, fontsize=8)

    ax.set_yticks(y, labels)
    ax.set_xlabel(f"Errors at $k={stats['k_headline']}$ (mean over runs)")
    ax.set_axisbelow(True)
    ax.grid(axis="y", visible=False)
    ax.set_xlim(0, max(left) * 1.10)
    # Below the axes, as in the degradation figure: an in-panel legend sat on
    # top of the shortest bar, which is the one the figure is arguing about.
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.30), ncol=4,
              frameon=False, fontsize=7.5, columnspacing=1.2,
              handlelength=1.4, handletextpad=0.5)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(f"{stem}.{ext}")
    plt.close(fig)


def table1(per_cell, stats, path):
    K = stats["k_headline"]
    by = defaultdict(list)
    for r in per_cell:
        if r["system"] == "S0" or int(r["k"]) == K:
            by[r["system"]].append(r)

    rows = []
    for system in ("S0", "S1", "S2", "S3"):
        cells = by.get(system, [])
        if not cells:
            continue
        acc, acc_sd = mean_sd([float(c["accuracy"]) for c in cells])
        accw, _ = mean_sd([float(c["accuracy_weighted"]) for c in cells])
        prec, _ = mean_sd([float(c["link_precision"]) for c in cells])
        rec, _ = mean_sd([float(c["link_recall"]) for c in cells])
        n, _ = mean_sd([float(c["mean_N"]) for c in cells])
        m, _ = mean_sd([float(c["mean_M"]) for c in cells])
        ci = stats.get(f"{system}_accuracy_ci95")
        ci_s = f"[{ci[0]:.3f}, {ci[1]:.3f}]" if ci else "--"
        if system == "S3":
            p_s = "--"
        else:
            p_s = (f"{stats['mcnemar_S2_vs_S3']['p_value']:.4f}"
                   if system == "S2" else "n/a")
        sd_s = f"\\,$\\pm$\\,{acc_sd:.3f}" if len(cells) > 1 else ""
        rows.append(
            f"{SYSTEM_LABEL[system]} & {acc:.3f}{sd_s} & {ci_s} & {accw:.3f} & "
            f"{prec:.3f} & {rec:.3f} & {n:.1f}\\,$\\to$\\,{m:.1f} & {p_s} \\\\")

    mc = stats["mcnemar_S2_vs_S3"]
    tex = [
        "% Main comparison at the headline k. Generated by report.py.",
        "% Requires: \\usepackage{booktabs}",
        r"\begin{table}[t]", r"\centering", r"\small",
        f"\\caption{{Entity linking on BME-EL at retrieval depth $k={K}$ "
        f"({stats['n_scored']} distinct mentions; {stats['n_excluded']} "
        f"\\texttt{{data\\_error}} mentions excluded). Accuracy is the mean over "
        f"3 runs at temperature~0 with the standard deviation where it is "
        f"non-zero; the 95\\% interval is a cluster bootstrap over objects "
        f"({stats['bootstrap']['resamples']} resamples). $N\\to M$ is the mean "
        f"number of candidates before and after symbolic validation. The final "
        f"column is McNemar's exact test against $S_3$.}}",
        r"\label{tab:el-main}",
        r"\begin{tabular}{lccccccc}", r"\toprule",
        r"System & Acc. & 95\% CI & Acc. (wt.) & Link prec. & Link rec. "
        r"& $N\to M$ & McNemar $p$ \\",
        r"\midrule", *rows, r"\bottomrule", r"\end{tabular}",
        r"\vspace{2pt}",
        f"\\par\\footnotesize Discordant pairs for $S_2$ vs.\\ $S_3$: "
        f"$b={mc['b_S2correct_S3wrong']}$ (only $S_2$ correct), "
        f"$c={mc['c_S2wrong_S3correct']}$ (only $S_3$ correct).",
        r"\end{table}",
    ]
    path.write_text("\n".join(tex) + "\n", encoding="utf-8")


def table2(per_type, stats, path):
    K = stats["k_headline"]
    rows = []
    for r in per_type:
        name = r["entity_type"]
        bold = name == "ALL"
        label = r"\textbf{Overall}" if bold else tex_escape(name)
        delta = float(r["delta"])
        d_s = f"{delta:+.3f}"
        if bold:
            d_s = f"\\textbf{{{d_s}}}"
        rows.append(
            f"{label} & {r['n_distinct']} / {r['n_instances']} & "
            f"{float(r[f'retrieval_recall@{K}']):.2f} & "
            f"{float(r['S1_accuracy']):.3f} & {float(r['S2_accuracy']):.3f} & "
            f"{float(r['S3_accuracy']):.3f} & {d_s} & "
            f"{float(r['validator_frr']):.2f} \\\\")
        if bold:
            rows.insert(-1, r"\midrule")
    tex = [
        "% Per entity type. Generated by report.py.",
        r"\begin{table}[t]", r"\centering", r"\small",
        f"\\caption{{Accuracy by entity type at $k={K}$, mean over 3 runs. "
        f"$n$ is distinct mentions / mention instances. Retrieval recall is the "
        f"share of non-NIL mentions whose gold entity appears in the frozen "
        f"top-{K} pool and bounds every system. FRR is the validator "
        f"false-rejection rate: gold entities retrieved but rejected by their "
        f"own \\textsc{{ask}} check. Types with fewer than 30 instances are "
        f"indicative only.}}",
        r"\label{tab:el-per-type}",
        r"\begin{tabular}{lccccccc}", r"\toprule",
        r"Entity type & $n$ & Ret.\ rec. & $S_1$ & $S_2$ & $S_3$ & $\Delta$ "
        r"& FRR \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}",
        r"\end{table}",
    ]
    path.write_text("\n".join(tex) + "\n", encoding="utf-8")


def table3(hard, stats, path, limit=8):
    K = stats["k_headline"]
    seen, rows = set(), []
    for h in hard:
        if h["entity_type"] in seen and len(rows) >= 4:
            continue                    # spread across types before repeating
        seen.add(h["entity_type"])
        gold = h["gold"]
        gold_s = (r"\textsc{nil}" if gold.startswith("NIL")
                  else f"\\texttt{{{gold}}}")
        s2 = (f"\\texttt{{{h['S2_predicted']}}} {tex_escape(h['S2_label'][:22])}"
              if h["S2_predicted"] != "-" else r"\textsc{nil}")
        rows.append(
            f"{tex_escape(h['label'][:24])} & {tex_escape(h['entity_type'])} & "
            f"{gold_s} & {s2} & {h['S2_outcome']} \\\\")
        if len(rows) >= limit:
            break
    tex = [
        "% Qualitative hard cases. Generated by report.py.",
        r"\begin{table}[t]", r"\centering", r"\small",
        f"\\caption{{Mentions the neuro-symbolic system $S_3$ resolves "
        f"correctly at $k={K}$ and the unvalidated system $S_2$ does not. "
        f"All are found in the collection, not constructed: cross-domain "
        f"homonyms, titles that read as ordinary language, and works whose "
        f"only Wikidata item is the corresponding single. WL~=~wrong link, "
        f"SL~=~spurious link.}}",
        r"\label{tab:el-hard}",
        r"\begin{tabular}{llllc}", r"\toprule",
        r"Mention & Type & Gold & $S_2$ chose & $S_2$ \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}",
    ]
    path.write_text("\n".join(tex) + "\n", encoding="utf-8")


def macros(per_cell, per_type, retrieval, frr, attribution, stats, path):
    """\\newcommand for every number quoted in prose, so the text cannot drift."""
    K = stats["k_headline"]
    at_k = defaultdict(list)
    for r in per_cell:
        if r["system"] == "S0" or int(r["k"]) == K:
            at_k[r["system"]].append(r)

    def m(system, field):
        return mean_sd([float(c[field]) for c in at_k[system]])[0]

    lines = ["% Generated by report.py — every number quoted in §4.4.",
             "% Regenerate after re-scoring; never edit by hand."]

    def cmd(name, value):
        lines.append(f"\\newcommand{{\\el{name}}}{{{value}}}")

    cmd("KHeadline", K)
    cmd("NMentions", stats["n_scored"])
    cmd("NExcluded", stats["n_excluded"])
    for s in ("S0", "S1", "S2", "S3"):
        if not at_k.get(s):
            continue
        cmd(f"{s}Acc", f"{m(s, 'accuracy'):.3f}")
        cmd(f"{s}Prec", f"{m(s, 'link_precision'):.3f}")
        cmd(f"{s}Rec", f"{m(s, 'link_recall'):.3f}")
        ci = stats.get(f"{s}_accuracy_ci95")
        if ci:
            cmd(f"{s}CI", f"[{ci[0]:.3f}, {ci[1]:.3f}]")
    cmd("DeltaAcc", f"{m('S3', 'accuracy') - m('S2', 'accuracy'):+.3f}")
    d = stats["delta_S3_minus_S2_ci95"]
    cmd("DeltaCI", f"[{d[0]:.3f}, {d[1]:.3f}]")
    mc = stats["mcnemar_S2_vs_S3"]
    cmd("McNemarP", f"{mc['p_value']:.4f}")
    cmd("McNemarB", mc["b_S2correct_S3wrong"])
    cmd("McNemarC", mc["c_S2wrong_S3correct"])
    cmd("PruneN", f"{m('S3', 'mean_N'):.1f}")
    cmd("PruneM", f"{m('S3', 'mean_M'):.1f}")
    overall = next(r for r in per_type if r["entity_type"] == "ALL")
    cmd("RetRecall", f"{float(overall[f'retrieval_recall@{K}']):.2f}")
    cmd("FRR", f"{float(overall['validator_frr']):.2f}")
    a3 = next((a for a in attribution if a["system"] == "S3"), None)
    a2 = next((a for a in attribution if a["system"] == "S2"), None)
    if a2 and a3:
        cmd("StwoSpurious", f"{float(a2['spurious_link']):.0f}")
        cmd("SthreeSpurious", f"{float(a3['spurious_link']):.0f}")
    # deepest/shallowest accuracy for the C2 sentence
    for s in ("S2", "S3"):
        vals = {int(r["k"]): [] for r in per_cell if r["system"] == s}
        for r in per_cell:
            if r["system"] == s:
                vals[int(r["k"])].append(float(r["accuracy"]))
        if vals:
            kmin, kmax = min(vals), max(vals)
            cmd(f"{s}AccKmin", f"{mean_sd(vals[kmin])[0]:.3f}")
            cmd(f"{s}AccKmax", f"{mean_sd(vals[kmax])[0]:.3f}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--results", type=Path, default=RESULTS)
    args = ap.parse_args(argv)
    R = args.results
    OUT.mkdir(parents=True, exist_ok=True)

    per_cell = read_csv(R / "per_cell.csv")
    per_type = read_csv(R / "per_type.csv")
    retrieval = read_csv(R / "retrieval.csv")
    frr = read_csv(R / "frr.csv")
    attribution = read_csv(R / "attribution.csv")
    hard = read_csv(R / "hard_cases.csv")
    stats = json.loads((R / "stats.json").read_text(encoding="utf-8"))

    figure(per_cell, stats, OUT / "figure_degradation.tex")
    table1(per_cell, stats, OUT / "table1_main.tex")
    table2(per_type, stats, OUT / "table2_per_type.tex")
    table3(hard, stats, OUT / "table3_hard_cases.tex")
    macros(per_cell, per_type, retrieval, frr, attribution, stats,
           OUT / "macros.tex")
    figure_pdf(per_cell, stats, str(OUT / "figure_degradation"))
    figure_attribution_pdf(attribution, stats, str(OUT / "figure_attribution"))
    for f in sorted(OUT.glob("*.tex")) + sorted(OUT.glob("*.pdf")) + \
            sorted(OUT.glob("*.png")):
        print(f"wrote {f.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
